#!/usr/bin/env python3
"""Makes zones.js: every tzdata time zone, the country it is in and its POSIX
TZ string, for the location the page gives an air unit after a flash (see
location.js). The units have no tzdata: a POSIX TZ string is what their C
library reads, and the country is what a named zone says (zone.tab) that the
string alone does not.

From tzdata: zone.tab (one country per zone), the zone files' footers (the
POSIX TZ string) and the link lines in tzdata.zi (old names a browser may still
report, like Asia/Calcutta). Run again to pick up a newer tzdata:

  tools/make-zones.py --tzdir /usr/share/zoneinfo > zones.js
"""
import argparse
import json
import os


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tzdir", default="/usr/share/zoneinfo")
    a = ap.parse_args()

    zones = {}
    for line in open(os.path.join(a.tzdir, "zone.tab"), encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        code, _, name = line.rstrip("\n").split("\t")[:3]
        data = open(os.path.join(a.tzdir, name), "rb").read()
        posix = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode()
        zones[name] = [code, posix]
    # UTC has no country: the zones of tzdata's "etcetera" a browser reports
    for name in ("Etc/UTC", "Etc/GMT"):
        zones[name] = ["", "UTC0" if name == "Etc/UTC" else "GMT0"]

    version, links = "", {}
    for line in open(os.path.join(a.tzdir, "tzdata.zi"), encoding="utf-8"):
        if line.startswith("# version"):
            version = line.split()[2]
        elif line.startswith("L "):
            _, target, alias = line.split()
            links[alias] = target
    # a link may name another link
    def resolve(name, depth=0):
        return resolve(links[name], depth + 1) if name in links and depth < 8 else name
    links = {k: resolve(v) for k, v in sorted(links.items()) if resolve(v) in zones and k not in zones}

    dump = lambda o: json.dumps(o, separators=(",", ":"), sort_keys=True, ensure_ascii=True)
    print("// Generated by tools/make-zones.py - do not edit.")
    print(f"// tzdata {version}: zone.tab, the zone files' POSIX TZ footers and tzdata.zi's links (public domain).")
    print(f"export const TZDATA_VERSION = {json.dumps(version)};")
    print("// zone: [ISO 3166 country code, POSIX TZ string]")
    print(f"export const ZONES = {dump(zones)};")
    print("// old or other name: the zone it is")
    print(f"export const LINKS = {dump(links)};")


if __name__ == "__main__":
    main()
